        _ENV["子线程上次执休息时间"] = tickCount()
      end
      if tickCount() - _ENV["子线程上次执休息时间"] > 60000 then
        _ENV["没有执行找到次数"] = _ENV["没有执行找到次数"] + 1
        if _ENV["没有执行找到次数"] >= 10 then
          if g_thread ~= nil then
            g_thread:stopThread()
          end
          sleep2(500)
          g_thread = Thread.newThread(_ENV["挂机模式"])
          _ENV["没有执行找到次数"] = 0
        end
      else
        _ENV["没有执行找到次数"] = 0
      end
    end
    if _ENV["当前任务1"]:find("活动模式") then
      local 应当执行的任务 = _ENV["当前任务1"]:gsub("活动模式", "")
      if _ENV["子线程上次执休息时间"] == nil then
        _ENV["子线程上次执休息时间"] = tickCount()
      end
      if tickCount() - _ENV["子线程上次执休息时间"] > 60000 then
        _ENV["没有执行找到次数"] = _ENV["没有执行找到次数"] + 1
        if _ENV["没有执行找到次数"] >= 10 then
          if g_thread ~= nil then
            g_thread:stopThread()
          end
          sleep2(500)
          g_thread = Thread.newThread(_ENV["活动模式"], 应当执行的任务)
          _ENV["没有执行找到次数"] = 0
        end
      else
        _ENV["没有执行找到次数"] = 0
      end
    end
  end
end

